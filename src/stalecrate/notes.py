"""Render agent notes from usage hits and upgrade-guide sections."""
import collections
import re

MEMBER_KINDS = ("function", "struct_field", "variant", "assoc_const", "assoc_type")
BEGIN, END = "<!-- stalecrate:begin", "<!-- stalecrate:end -->"


def key_name(h):
    """How an item is named for matching and display: `Owner::member` for members
    (a bare `Add` or `new` names too many things), the item name otherwise."""
    segs = re.split(r"::|\.", h["path"])
    member = len(segs) > 2 and segs[-2][:1].isupper() and h.get("kind") in MEMBER_KINDS
    return f"{segs[-2]}::{segs[-1]}" if member else segs[-1]


def mentions(text, name):
    """`name` inside inline code. Short names (On, Or, Val) must look like code
    use (`On<`, `On::`, `On(`), not appear as a word in some other snippet."""
    n = re.escape(name)
    if len(name) <= 4:
        return re.search(rf"`[^`\n]*\b{n}(?:<|::|\()[^`\n]*`", text) is not None
    return re.search(rf"`[^`\n]*\b{n}\b[^`\n]*`", text) is not None


def match_sections(hits, sections):
    """Link each hit to the guide sections about it. A section whose title names
    the item wins over sections that mention it in passing; items that moved to
    a new crate share the section announcing that crate."""
    sec_hits = collections.defaultdict(list)
    unmatched = []
    for h in hits:
        name = key_name(h)
        m = [i for i, s in enumerate(sections) if mentions(s.title, name)]
        if not m and h["change"] == "moved":
            dests = {p.split("::")[0] for p in h["moved_to"]}
            m = [i for i, s in enumerate(sections) if any(mentions(s.title, d) for d in dests)]
        if not m:
            m = [i for i, s in enumerate(sections) if mentions(s.body, name)]
        for i in m[:2]:
            sec_hits[i].append(h)
        if not m:
            unmatched.append(h)
    return sec_hits, unmatched


def excerpt(body, names, limit=900):
    """Opening paragraphs up to `limit` chars, plus any later line that names a
    used item (`- SceneRoot -> WorldAssetRoot` in a long rename list)."""
    body = re.sub(r"\{\{.*?\}\}", "", body).strip()
    paras = re.split(r"\n\s*\n", body)
    out, size, i = [], 0, 0
    while i < len(paras) and (size + len(paras[i]) <= limit or not out):
        out.append(paras[i].strip()); size += len(paras[i]); i += 1
    rest = "\n\n".join(paras[i:])
    extra = [ln.strip() for ln in rest.splitlines() if ln.strip() and any(mentions(ln, n) for n in names)]
    if extra:
        out.append("\n".join(dict.fromkeys(extra[:12])))
    return "\n\n".join(out)


def one_line(h):
    key = key_name(h)
    if h["change"] == "moved":
        return f"`{key}` moved to `{sorted(h['moved_to'], key=len)[0]}`"
    if h["change"] == "deprecated":
        note = h.get("note")
        return f"`{key}` is deprecated: {note.get('note') if isinstance(note, dict) else note}"
    if h["change"] == "removed":
        line = f"`{key}` was removed in {h['crate']} {h['new']}"
        if h.get("siblings_added"):
            name = key.rsplit("::", 1)[-1]
            # likely replacements first: `PointerClick` for a removed `Click`
            sib = sorted(h["siblings_added"], key=lambda x: (not x.endswith(name), name.lower() not in x.lower(), x))
            where = f"`{key.rsplit('::', 1)[0]}` gained" if "::" in key else f"new in `{h['path'].rsplit('::', 1)[0]}`"
            line += f"; {where}: " + ", ".join(f"`{x}`" for x in sib[:5])
        return line
    if h.get("old_sig") and h.get("new_sig") and h["old_sig"] != h["new_sig"]:
        return f"`{key}` changed: `{h['old_sig']}` → `{h['new_sig']}`"
    return f"`{key}` changed signature in {h['crate']} {h['new']}"


def tokens(text):
    return len(text) // 4   # rough: ~4 characters per token for English and code


def render(families, cutoff_label, max_tokens=4000, inputs=""):
    """families: [{name, base, pinned, hits, sections}] (one per direct dependency
    family, e.g. all bevy_* crates under `bevy`). Sections are added in order of
    how many project files they touch until the token budget runs out."""
    head = [f"{BEGIN} inputs={inputs} -->", f"## Dependencies that changed after {cutoff_label}", "",
            "These crates are pinned at versions released after your training data. Their APIs differ "
            "from what you remember; check here before using them. Generated by stalecrate.", ""]
    blocks = []   # (score, text)
    for fam in families:
        hits = [h for h in fam["hits"] if h["change"] != "bounds"]   # bound-only changes rarely break callers
        if not hits:
            continue
        sec_hits, unmatched = match_sections(hits, fam["sections"])
        blocks.append((10**9, f"### {fam['name']} {fam['base']} → {fam['pinned']}\n"))
        ranked = sorted(sec_hits.items(), key=lambda kv: -len(set().union(*(h["files"] for h in kv[1]))))
        for i, hs in ranked:
            s = fam["sections"][i]
            files = set().union(*(h["files"] for h in hs))
            names = sorted({key_name(h) for h in hs})
            text = (f"#### {s.title}\n({s.source}; your code uses {', '.join(f'`{n}`' for n in names[:6])} "
                    f"in {len(files)} file{'s' * (len(files) != 1)})\n\n{excerpt(s.body, names)}\n")
            blocks.append((len(files), text))
        seen = set()
        if unmatched:
            top = max(len(h["files"]) for h in unmatched)
            blocks.append((top - 0.4, "#### Other API changes your code touches\n"))
        for h in sorted(unmatched, key=lambda h: -len(h["files"])):
            if key_name(h) in seen:
                continue
            seen.add(key_name(h))
            blocks.append((len(h["files"]) - 0.5, f"- {one_line(h)} (used in {len(h['files'])} files)\n"))
    budget = max_tokens - tokens("\n".join(head)) - 20
    chosen = set()
    for idx, (score, text) in sorted(enumerate(blocks), key=lambda x: -x[1][0]):
        if tokens(text) <= budget:
            chosen.add(idx); budget -= tokens(text)
    dropped = len(blocks) - len(chosen)
    body = "\n".join(text for idx, (_, text) in enumerate(blocks) if idx in chosen)
    tail = [f"\n({dropped} lower-ranked entries left out to stay under {max_tokens} tokens; "
            f"run `stalecrate sync --max-tokens N` for more.)" if dropped else "", END]
    return "\n".join(head) + "\n" + body + "\n".join(tail) + "\n"


def write_block(path, block):
    """Insert or replace the stalecrate block in AGENTS.md / CLAUDE.md."""
    text = path.read_text() if path.exists() else ""
    if BEGIN in text and END in text:
        start, end = text.index(BEGIN), text.index(END) + len(END)
        new = text[:start] + block.rstrip("\n") + text[end:]
    else:
        new = (text.rstrip("\n") + "\n\n" if text.strip() else "") + block
    if new != text:
        path.write_text(new)
    return new != text
